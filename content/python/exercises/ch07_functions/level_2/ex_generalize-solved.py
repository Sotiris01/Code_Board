def emvado_trigwnou(vasi, ypsos):
    return vasi * ypsos / 2

# Τώρα: 3 κλήσεις αντί 9 γραμμές!
print("Εμβαδό 1:", emvado_trigwnou(10, 5))
print("Εμβαδό 2:", emvado_trigwnou(8, 3))
print("Εμβαδό 3:", emvado_trigwnou(12, 7))

