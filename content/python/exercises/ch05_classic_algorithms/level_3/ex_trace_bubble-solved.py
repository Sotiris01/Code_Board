# ΑΣΚΗΣΗ: Ιχνηλάτηση Bubble Sort - ΛΥΣΗ

# A = [5, 3, 8, 1]
#
# Πέρασμα i=0:
#   j=3: A[3]=1 < A[2]=8 → αντιμ. → [5, 3, 1, 8]
#   j=2: A[2]=1 < A[1]=3 → αντιμ. → [5, 1, 3, 8]
#   j=1: A[1]=1 < A[0]=5 → αντιμ. → [1, 5, 3, 8]
#   Μετά i=0: [1, 5, 3, 8]  (το 1 "ανέβηκε" στη θέση 0)
#
# Πέρασμα i=1:
#   j=3: A[3]=8 < A[2]=3 → ΟΧΙ     → [1, 5, 3, 8]
#   j=2: A[2]=3 < A[1]=5 → αντιμ. → [1, 3, 5, 8]
#   Μετά i=1: [1, 3, 5, 8]  (το 3 "ανέβηκε" στη θέση 1)
#
# Πέρασμα i=2:
#   j=3: A[3]=8 < A[2]=5 → ΟΧΙ     → [1, 3, 5, 8]
#   Μετά i=2: [1, 3, 5, 8]  (ήδη ταξινομημένη)
#
# Συνολικά: 6 ΣΥΓΚΡΙΣΕΙΣ, 4 ΑΝΤΙΜΕΤΑΘΕΣΕΙΣ

# Επαλήθευση με κώδικα:
def bubbleSortTrace(A):
    N = len(A)
    sygkriseis = 0
    antimetatheiseis = 0
    for i in range(N - 1):
        for j in range(N - 1, i, -1):
            sygkriseis += 1
            if A[j] < A[j - 1]:
                A[j], A[j - 1] = A[j - 1], A[j]
                antimetatheiseis += 1
        print(f"Μετά i={i}: {A}")
    print(f"Συγκρίσεις: {sygkriseis}, Αντιμεταθέσεις: {antimetatheiseis}")

data = [5, 3, 8, 1]
print("Αρχικά:", data)
bubbleSortTrace(data)
