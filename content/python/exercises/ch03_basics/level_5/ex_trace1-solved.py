# === ΜΕΡΟΣ Α ===
# Αυτή είναι αντιμετάθεση ΧΩΡΙΣ temp!
x = 5
y = 10
z = x + y    # z = 15
x = z - x    # x = 15 - 5 = 10
y = z - y    # y = 15 - 10 = 5
print("A:", x, y, z)
# Απάντηση Α: A: 10 5 15  (τα x,y αντιμεταθέτηκαν!)

# === ΜΕΡΟΣ Β ===
a = 7
b = a // 2   # b = 3 (ακέραια διαίρεση)
c = a % 2    # c = 1 (υπόλοιπο)
a = b * 10 + c  # a = 30 + 1 = 31
print("B:", a, b, c)
# Απάντηση Β: B: 31 3 1

# === ΜΕΡΟΣ Γ ===
p = 100
p = p + 10   # p = 110
p = p - 20   # p = 90
q = p * 2    # q = 180
p = p / q    # p = 90/180 = 0.5 (float!)
print("C:", p, q)
# Απάντηση Γ: C: 0.5 180
