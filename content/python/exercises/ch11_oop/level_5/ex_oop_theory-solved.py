# 1. Βασικά χαρακτηριστικά OOP:
#    - Κλάσεις: πρότυπα για τη δημιουργία αντικειμένων
#    - Αντικείμενα: στιγμιότυπα κλάσεων με ιδιότητες και μεθόδους
#    - Κληρονομικότητα: μεταβίβαση ιδιοτήτων/μεθόδων σε υποκλάσεις
#    - Πολυμορφισμός: ομώνυμες μέθοδοι με διαφορετική συμπεριφορά
#    - Ενθυλάκωση: απόκρυψη υλοποίησης, πρόσβαση μόνο μέσω μεθόδων

# 2. Διαφορά OOP vs Δομημένος:
#    - OOP: εστίαση σε αντικείμενα (δεδομένα + λειτουργίες μαζί)
#    - Δομημένος: εστίαση σε διαδικασίες (συναρτήσεις που επεξεργάζονται δεδομένα)

# 3. Κλάση vs Αντικείμενο:
#    - Κλάση = πρότυπο/συνταγή (class Dog:)
#    - Αντικείμενο = στιγμιότυπο (max = Dog("terrier", ...))
#    - Μια κλάση μπορεί να δημιουργήσει πολλά αντικείμενα

# 4. Δήλωση κλάσης στην Python:

class Paradeigma:
    def __init__(self, onoma):   # constructor
        self.onoma = onoma       # ιδιότητα (self.attr = param)

    def emfanise(self):          # μέθοδος
        print(self.onoma)

obj = Paradeigma("Τεστ")        # δημιουργία αντικειμένου
obj.emfanise()                   # κλήση μεθόδου → Τεστ

# 5. Κληρονομικότητα:
#    Μεταβίβαση ιδιοτήτων και μεθόδων από γονική σε θυγατρική κλάση.

class Gonea:
    def __init__(self, name):
        self.name = name

class Paidi(Gonea):              # κληρονομεί τη Gonea
    def __init__(self, name, age):
        super().__init__(name)   # κλήση constructor γονέα
        self.age = age

p = Paidi("Γιάννης", 15)
print(p.name)         # → Γιάννης (κληρονομημένη)
print(p.age)          # → 15 (δική της)

# 6. Πολυμορφισμός:
#    Η ίδια μέθοδος συμπεριφέρεται διαφορετικά σε διαφορετικές κλάσεις.

class Dog:
    def speak(self):
        print("Γαβ!")

class Cat:
    def speak(self):
        print("Νιάου!")

animals = [Dog(), Cat()]
for a in animals:
    a.speak()           # → Γαβ! / Νιάου! (πολυμορφισμός)

