# ΑΣΚΗΣΗ: Αντιμετάθεση Τιμών - ΛΥΣΗ

a = int(input("Δώσε a: "))
b = int(input("Δώσε b: "))

print("Πριν: a =", a, "b =", b)

# Τρόπος Α: Με βοηθητική μεταβλητή
temp = a
a = b
b = temp

print("Μετά (τρόπος Α): a =", a, "b =", b)

# Τρόπος Β: Python swap
a, b = b, a   # ξαναγυρνάμε στα αρχικά

print("Μετά (τρόπος Β): a =", a, "b =", b)
