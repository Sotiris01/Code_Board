# 1. Η κλάση είναι ένα πρότυπο (template) για τη δημιουργία αντικειμένων.
#    Απάντηση: Σ
#    Η κλάση ορίζει τη δομή (ιδιότητες) και τη συμπεριφορά (μεθόδους).

# 2. Κάθε αντικείμενο πρέπει να ανήκει σε μια κλάση.
#    Απάντηση: Σ
#    Στην Python, κάθε τιμή είναι αντικείμενο κάποιας κλάσης.

# 3. Η μέθοδος __init__ καλείται χειροκίνητα μετά τη δημιουργία αντικειμένου.
#    Απάντηση: Λ
#    Η __init__ καλείται ΑΥΤΟΜΑΤΑ κατά τη δημιουργία (constructor).

# 4. Η παράμετρος self αναφέρεται στο τρέχον αντικείμενο.
#    Απάντηση: Σ
#    Το self είναι αναφορά στο αντικείμενο που καλεί τη μέθοδο.

# 5. Μια μεταβλητή κλάσης είναι κοινή για ΟΛΑ τα αντικείμενα.
#    Απάντηση: Σ
#    Class variable: κοινή τιμή, πρόσβαση μέσω ClassName.var

# 6. Η κληρονομικότητα επιτρέπει σε μια κλάση να "κληρονομήσει"
#    ιδιότητες και μεθόδους από άλλη κλάση.
#    Απάντηση: Σ
#    class Child(Parent)  →  η Child κληρονομεί τα πάντα από Parent.

# 7. Ο πολυμορφισμός σημαίνει ότι μια μέθοδος μπορεί να έχει
#    διαφορετική συμπεριφορά σε διαφορετικές κλάσεις.
#    Απάντηση: Σ
#    Π.χ. getArea() υπολογίζει διαφορετικά σε Square vs Circle.

# 8. Η ενθυλάκωση (encapsulation) σημαίνει ότι όλες οι ιδιότητες
#    είναι προσβάσιμες απ' ευθείας.
#    Απάντηση: Λ
#    Ενθυλάκωση = ΑΠΟΚΡΥΨΗ υλοποίησης. Πρόσβαση ΜΟΝΟ μέσω μεθόδων.

# --- Παράδειγμα κώδικα ---

class MyClass:
    class_var = 0                    # μεταβλητή κλάσης (κοινή)

    def __init__(self, value):       # constructor (αυτόματη κλήση)
        self.value = value           # self = τρέχον αντικείμενο
        MyClass.class_var += 1

obj = MyClass(10)                    # __init__ καλείται αυτόματα
print(obj.value)                     # → 10
print(MyClass.class_var)             # → 1
