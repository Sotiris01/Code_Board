# ΣΕΝΑΡΙΟ 1:
total = 0

def my_sum(a, b):
    total = a + b        # ΤΟΠΙΚΗ μεταβλητή!
    print("Μέσα:", total)
    return total

my_sum(10, 20)
print("Έξω:", total)
# Γραμμή 1: Μέσα: 30    (τοπική total = 30)
# Γραμμή 2: Έξω: 0      (η ΚΑΘΟΛΙΚΗ total ΔΕΝ αλλάζει!)
# Γιατί: Η total μέσα στη συνάρτηση είναι ΤΟΠΙΚΗ
#         (τη δημιούργησε η εκχώρηση total = a + b)
#         Η global total παραμένει 0.

print("---")

# ΣΕΝΑΡΙΟ 2:
x = 50
def func(x):
    print("Παράμετρος:", x)
    x = 2
    print("Τοπικό:", x)

func(x)
print("Έξω:", x)
# Γραμμή 1: Παράμετρος: 50  (πήρε τιμή από argument)
# Γραμμή 2: Τοπικό: 2       (τοπική x αλλάζει)
# Γραμμή 3: Έξω: 50         (η global x δεν αλλάζει)
