/*
 * Άσκηση: Επικύρωση Εισόδου με While
 * Επίπεδο: 1
 * 
 * Περιγραφή:
 * Ζήτα από τον χρήστη έναν βαθμό (0-20).
 * Αν δώσει λάθος τιμή, ζήτα ξανά μέχρι να δώσει σωστή.
 * Τέλος, εμφάνισε αν πέρασε (>= 10) ή απέτυχε.
 */

#include <iostream>
using namespace std;

int main() {
    int grade;
    
    cout << "Δώσε βαθμό (0-20): ";
    cin >> grade;
    
    // ΛΥΣΗ: While loop για επικύρωση
    while (grade < 0 || grade > 20) {
        cout << "Λάθος! Ξαναδώσε (0-20): ";
        cin >> grade;
    }
    
    // ΛΥΣΗ: Έλεγχος επιτυχίας
    if (grade >= 10) {
        cout << "Πέρασες με " << grade << "!" << endl;
    } else {
        cout << "Απέτυχες με " << grade << endl;
    }
    
    return 0;
}
