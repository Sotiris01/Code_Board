# ΑΣΚΗΣΗ: Ανάγνωση Γραμμή-Γραμμή - ΛΥΣΗ

# Δημιουργία αρχείου
f = open("fruits.txt", "w")
f.write("Μήλο\n")
f.write("Μπανάνα\n")
f.write("Πορτοκάλι\n")
f.write("Σταφύλι\n")
f.write("Καρπούζι\n")
f.close()

# Ανάγνωση γραμμή-γραμμή
print("=== Με κενές γραμμές ===")
f = open("fruits.txt", "r")
for line in f:
    print(line)          # τυπώνει κενή γραμμή ανάμεσα
f.close()

print("=== Χωρίς κενές γραμμές ===")
f = open("fruits.txt", "r")
for line in f:
    print(line, end="")  # αφαιρεί την extra αλλαγή γραμμής
f.close()

# ΕΞΗΓΗΣΗ: Η κάθε γραμμή τελειώνει με "\n"
# και η print() προσθέτει κι αυτή ένα "\n".
# Αποτέλεσμα: 2 αλλαγές γραμμής → κενή γραμμή!
# Λύση: end="" ή strip()
