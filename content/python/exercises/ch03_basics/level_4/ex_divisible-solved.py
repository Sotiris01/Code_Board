# ΑΣΚΗΣΗ: Διαιρετότητα - ΛΥΣΗ

x = int(input("Δώσε αριθμό: "))

div2 = x % 2 == 0
div3 = x % 3 == 0

if div2 and div3:
    print("Ο", x, "διαιρείται και με το 2 και με το 3")
elif div2:
    print("Ο", x, "διαιρείται μόνο με το 2")
elif div3:
    print("Ο", x, "διαιρείται μόνο με το 3")
else:
    print("Ο", x, "δεν διαιρείται ούτε με το 2 ούτε με το 3")
