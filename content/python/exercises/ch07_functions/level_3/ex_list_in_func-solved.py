# ΑΣΚΗΣΗ: Λίστα σε Συνάρτηση — Παγίδα! - ΛΥΣΗ

# ΠΕΡΙΠΤΩΣΗ Α: append → ΑΛΛΑΖΕΙ πρωτότυπο
def changeme_a(mylist):
    mylist.append([1, 2, 3])

L = [10, 20, 30]
changeme_a(L)
print(L)
# ΑΠΑΝΤΗΣΗ Α: [10, 20, 30, [1, 2, 3]]
# Η append τροποποιεί ΤΗΝ ΙΔΙΑ λίστα!

print("---")

# ΠΕΡΙΠΤΩΣΗ Β: εκχώρηση → ΔΕΝ αλλάζει
def changeme_b(mylist):
    mylist = [1, 2, 3]     # ΝΕΑ τοπική μεταβλητή!

L = [10, 20, 30]
changeme_b(L)
print(L)
# ΑΠΑΝΤΗΣΗ Β: [10, 20, 30]
# Η εκχώρηση mylist = [1,2,3] δημιουργεί
# ΝΕXΑ τοπική μεταβλητή. Η αρχική L δεν αλλάζει.

# ΚΑΝΟΝΑΣ:
# - append/insert/pop → τροποποιούν ΤΗΝ ΙΔΙΑ λίστα
# - εκχώρηση (=) → δημιουργεί ΝΕΑ τοπική μεταβλητή
