/*
 * ΑΣΚΗΣΗ: Φιλτράρισμα αριθμών
 * 
 * Ο χρήστης δίνει πρώτα τον αριθμό N (πλήθος αριθμών).
 * Στη συνέχεια εισάγει N ακέραιους αριθμούς (θετικούς, αρνητικούς ή μηδέν).
 * Το πρόγραμμα κρατάει μόνο τους θετικούς ζυγούς αριθμούς
 * και εμφανίζει το άθροισμά τους και το πλήθος τους.
 * Αν δεν βρεθεί κανένας θετικός ζυγός, εμφανίζεται κατάλληλο μήνυμα.
 */

#include <iostream>
using namespace std;

int main() {
    int n, num;
    int sum = 0, count = 0;
    
    cout << "Πόσοι αριθμοί; ";
    cin >> n;
    
    for (int i = 0; i < n; i++) {
        cout << "Αριθμός: ";
        cin >> num;
        
        if (num > 0 && num % 2 == 0) {
            sum += num;
            count++;
        }
    }
    
    cout << "Άθροισμα: " << sum << endl;
    cout << "Πλήθος: " << count << endl;
    
    return 0;
}
