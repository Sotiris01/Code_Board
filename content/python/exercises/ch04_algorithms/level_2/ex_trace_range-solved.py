# ΑΣΚΗΣΗ: Ιχνηλάτηση range() - ΛΥΣΗ

# --- Κώδικας ---
for i in range(5):
    print(i, end=" ")
print()
for i in range(2, 8):
    print(i, end=" ")
print()
for i in range(1, 10, 2):
    print(i, end=" ")
print()
for i in range(10, 0, -2):
    print(i, end=" ")

