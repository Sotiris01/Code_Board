/*
 * ΑΣΚΗΣΗ: Ανάλυση ψηφίων αριθμού
 * 
 * Ο χρήστης εισάγει έναν θετικό ακέραιο.
 * Αν δώσει αρνητικό ή 0, του ζητείται ξανά.
 * Το πρόγραμμα υπολογίζει και εμφανίζει:
 *   - Το πλήθος των ψηφίων
 *   - Το άθροισμα των ψηφίων
 *   - Το μεγαλύτερο ψηφίο
 *   - Το μικρότερο ψηφίο
 * Παράδειγμα: 3825 → πλήθος=4, άθροισμα=18, μεγ=8, μικ=2
 */

#include <iostream>
using namespace std;

int main() {
    int num, digit;
    int sum = 0, count = 0;
    
    cout << "Αριθμός: ";
    cin >> num;
    
    int temp = num;
    while (temp > 0) {
        digit = temp % 10;
        sum += digit;
        count++;
        temp = temp / 10;
    }
    
    cout << "Άθροισμα ψηφίων: " << sum << endl;
    cout << "Πλήθος ψηφίων: " << count << endl;
    
    return 0;
}
