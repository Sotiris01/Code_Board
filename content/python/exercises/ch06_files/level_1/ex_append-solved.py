# ΑΣΚΗΣΗ: Προσθήκη σε Αρχείο (Append) - ΛΥΣΗ

# Βήμα 1: Δημιουργία
f = open("log.txt", "w")
f.write("Ημέρα 1: Ξεκίνησα Python\n")
f.close()

# Βήμα 2: Προσθήκη (append)
f = open("log.txt", "a")
f.write("Ημέρα 2: Έμαθα αρχεία\n")
f.write("Ημέρα 3: Έκανα ασκήσεις\n")
f.close()

# Βήμα 3: Ανάγνωση
f = open("log.txt", "r")
print(f.read())
f.close()

# ΑΠΑΝΤΗΣΗ: Αν χρησιμοποιούσαμε "w" αντί "a",
# θα ΣΒΗΝΟΝΤΑΝ τα υπάρχοντα δεδομένα και
# θα μένανε μόνο οι γραμμές του βήματος 2.
# Η "Ημέρα 1" θα χανόταν!
