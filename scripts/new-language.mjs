#!/usr/bin/env node
/**
 * scripts/new-language.mjs — Phase 5.5 scaffolder.
 *
 * Usage:
 *   npm run new:lang -- <id> [label] [ext]
 *
 * Examples:
 *   npm run new:lang -- ruby Ruby .rb
 *   npm run new:lang -- go   Go   .go
 *
 * Generates:
 *   src/languages/<id>/{plugin,keywords,snippets,syntax,content}.js
 *   public/assets/icons/<id>.svg   (monogram placeholder)
 *   Appends <id> to src/languages/registry.json
 *   Inserts a <script src="src/languages/<id>/plugin.js"> tag into
 *   public/index.html (just after the existing plugin descriptors).
 *
 * Idempotent: refuses to overwrite an existing language id.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');

const [, , idArg, labelArg, extArg] = process.argv;
if (!idArg) {
    console.error('Usage: npm run new:lang -- <id> [label] [ext]');
    process.exit(1);
}

const id = idArg.toLowerCase().replace(/[^a-z0-9_-]/g, '');
const label = labelArg || (id[0].toUpperCase() + id.slice(1));
const ext = (extArg || `.${id}`).startsWith('.') ? (extArg || `.${id}`) : `.${extArg}`;
const namespace = id[0].toUpperCase() + id.slice(1);
const iconFile = `${id}.svg`;

const REGISTRY = path.join(ROOT, 'src', 'languages', 'registry.json');
const LANG_DIR = path.join(ROOT, 'src', 'languages', id);
const ICON_FILE = path.join(ROOT, 'public', 'assets', 'icons', iconFile);
const INDEX_HTML = path.join(ROOT, 'public', 'index.html');

async function exists(p) {
    try { await fs.access(p); return true; } catch { return false; }
}

if (await exists(LANG_DIR)) {
    console.error(`Language directory already exists: ${LANG_DIR}`);
    process.exit(1);
}

// ---- 1. Update registry.json --------------------------------------
const registry = JSON.parse(await fs.readFile(REGISTRY, 'utf-8'));
if (registry.languages.some(l => l.id === id)) {
    console.error(`Language id "${id}" already in registry.json`);
    process.exit(1);
}
registry.languages.push({
    id, label, namespace,
    fileExtensions: [ext],
    icon: iconFile,
    commentSyntax: { line: '//', block: ['/*', '*/'] },
    indentTriggers: ['{'],
    dedentTriggers: ['}'],
    autoPairs: { '(': ')', '[': ']', '{': '}', '"': '"', "'": "'" }
});
await fs.writeFile(REGISTRY, JSON.stringify(registry, null, 2) + '\n', 'utf-8');

// ---- 2. Generate language module files ----------------------------
await fs.mkdir(LANG_DIR, { recursive: true });

const pluginJs = `/**
 * ${label} language plugin descriptor (generated by new-language.mjs).
 */
(function () {
    if (typeof LanguageRegistry === 'undefined') return;
    LanguageRegistry.register({
        id: '${id}',
        label: '${label}',
        namespace: '${namespace}',
        fileExtensions: ['${ext}'],
        commentSyntax: { line: '//', block: ['/*', '*/'] },
        indentTriggers: ['{'],
        dedentTriggers: ['}'],
        autoPairs: { '(': ')', '[': ']', '{': '}', '"': '"', "'": "'" },
        icon: '${iconFile}'
    });
})();
`;

const keywordsJs = `window.Languages = window.Languages || {};
window.Languages.${namespace} = window.Languages.${namespace} || {};
window.Languages.${namespace}.keywords = [
    // TODO: add ${label} keywords here.
];
`;

const snippetsJs = `window.Languages = window.Languages || {};
window.Languages.${namespace} = window.Languages.${namespace} || {};
window.Languages.${namespace}.snippets = {
    // TODO: add ${label} snippets here. Example:
    // 'hello': 'print("hello world")'
};
`;

const syntaxJs = `window.Languages = window.Languages || {};
window.Languages.${namespace} = window.Languages.${namespace} || {};
/**
 * Minimal syntax highlighter for ${label}.
 * Receives raw code, returns HTML with <span class="..."> tokens.
 * TODO: replace this stub with real tokenization.
 */
window.Languages.${namespace}.highlight = function (code) {
    return code
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;');
};
`;

const contentJs = `window.Languages = window.Languages || {};
window.Languages.${namespace} = window.Languages.${namespace} || {};
window.Languages.${namespace}.content = {
    sidebar: { sections: [] },
    initialCode: '// Hello from ${label}\\n'
};
`;

await fs.writeFile(path.join(LANG_DIR, 'plugin.js'), pluginJs);
await fs.writeFile(path.join(LANG_DIR, 'keywords.js'), keywordsJs);
await fs.writeFile(path.join(LANG_DIR, 'snippets.js'), snippetsJs);
await fs.writeFile(path.join(LANG_DIR, 'syntax.js'), syntaxJs);
await fs.writeFile(path.join(LANG_DIR, 'content.js'), contentJs);

// ---- 3. Icon (monogram placeholder) -------------------------------
if (!(await exists(ICON_FILE))) {
    const initials = label.slice(0, 2);
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24"><rect width="24" height="24" rx="4" fill="#555"/><text x="12" y="17" font-family="Segoe UI,Arial,sans-serif" font-size="11" font-weight="700" text-anchor="middle" fill="#fff">${initials}</text></svg>\n`;
    await fs.writeFile(ICON_FILE, svg);
}

// ---- 4. Wire <script> into public/index.html ----------------------
let html = await fs.readFile(INDEX_HTML, 'utf-8');
const tag = `    <script src="src/languages/${id}/plugin.js?v=1"></script>\n`;
if (!html.includes(tag)) {
    const anchor = '    <script src="src/languages/java/plugin.js?v=1"></script>\n';
    if (html.includes(anchor)) {
        html = html.replace(anchor, anchor + tag);
        await fs.writeFile(INDEX_HTML, html, 'utf-8');
    } else {
        console.warn('Could not auto-insert <script> tag — add it manually:');
        console.warn('  ' + tag.trim());
    }
}

console.log(`✅ Created ${label} (${id}) — files at src/languages/${id}/`);
console.log(`   Next steps:`);
console.log(`   1. Edit src/languages/${id}/{keywords,snippets,syntax,content}.js`);
console.log(`   2. Replace public/assets/icons/${iconFile} with a real icon`);
console.log(`   3. Restart npm start and reload the browser`);
