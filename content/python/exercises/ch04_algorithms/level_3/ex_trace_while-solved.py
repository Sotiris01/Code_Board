# ΑΣΚΗΣΗ: Ιχνηλάτηση while - ΛΥΣΗ

x = 1
y = 0
while x <= 10:
    y = y + x
    x = x + 3
print("x =", x)
print("y =", y)

# Πίνακας Ιχνηλάτησης:
# Βήμα | x  | y  | x<=10
# -----|----|----|------
#  0   | 1  | 0  | True
#  1   | 4  | 1  | True    (y=0+1=1, x=1+3=4)
#  2   | 7  | 5  | True    (y=1+4=5, x=4+3=7)
#  3   | 10 | 12 | True    (y=5+7=12, x=7+3=10)
#  4   | 13 | 22 | False   (y=12+10=22, x=10+3=13)
#
# Τελική Έξοδος:
# x = 13
# y = 22
