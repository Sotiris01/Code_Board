# ΑΣΚΗΣΗ: Πίνακας Modes Αρχείων - ΛΥΣΗ

# | Mode | Λειτουργία | Αν υπάρχει;           | Αν ΔΕΝ υπάρχει;  |
# |------|------------|-----------------------|-------------------|
# | "r"  | Ανάγνωση   | Διαβάζει              | ΣΦΑΛΜΑ            |
# | "w"  | Εγγραφή    | ΣΒΗΝΕΙ ΟΛΑ & γράφει  | Δημιουργεί νέο    |
# | "a"  | Προσθήκη   | Κρατάει + γράφει τέλος| Δημιουργεί νέο    |

# 1. Αν ανοίξω ένα υπάρχον αρχείο με "w",
#    τι θα γίνει με τα δεδομένα του;
#    Απάντηση: ΘΑ ΣΒΗΣΤΟΥΝ ΟΛΑ! Το "w" αδειάζει
#    πλήρως το αρχείο πριν γράψει.

# 2. Ποιο mode χρησιμοποιώ αν θέλω να
#    ΠΡΟΣΘΕΣΩ δεδομένα χωρίς να χάσω
#    τα υπάρχοντα;
#    Απάντηση: "a" (append). Γράφει στο τέλος
#    του αρχείου, χωρίς να σβήσει τίποτα.

# 3. Τι σφάλμα θα πάρω αν ανοίξω
#    ανύπαρκτο αρχείο με "r";
#    Απάντηση: FileNotFoundError
#    (δεν βρέθηκε το αρχείο)
