# ΑΛΓΟΡΙΘΜΟΣ:
# Για κάθε i (1 ως len-1):
#   1. Αποθήκευσε value = array[i]
#   2. j = i
#   3. Όσο j > 0 ΚΑΙ array[j-1] > value:
#      - Μετακίνησε array[j-1] μια θέση δεξιά
#      - j = j - 1
#   4. Τοποθέτησε value στη θέση j
#
# Δοκίμασε με:
#   data = [7, 2, 9, 4, 1, 5]
#   insertionSort(data)
#   print(data) → [1, 2, 4, 5, 7, 9]

