# ΑΣΚΗΣΗ: Ημέρα της Εβδομάδας - ΛΥΣΗ

mera = int(input("Δώσε αριθμό (1-7): "))

if mera == 1:
    print("Δευτέρα")
elif mera == 2:
    print("Τρίτη")
elif mera == 3:
    print("Τετάρτη")
elif mera == 4:
    print("Πέμπτη")
elif mera == 5:
    print("Παρασκευή")
elif mera == 6:
    print("Σάββατο")
elif mera == 7:
    print("Κυριακή")
else:
    print("Μη έγκυρη ημέρα!")
