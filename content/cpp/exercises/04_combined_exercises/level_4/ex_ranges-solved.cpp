/*
 * ΑΣΚΗΣΗ: Κατηγοριοποίηση σε διαστήματα
 * 
 * Ο χρήστης εισάγει αριθμούς μέχρι να δώσει 0 (τερματισμός).
 * Κάθε αριθμός κατατάσσεται σε μία από τρεις κατηγορίες:
 *   - Μικροί: κάτω από 10
 *   - Μεσαίοι: από 10 έως 50 (συμπεριλαμβανομένων)
 *   - Μεγάλοι: πάνω από 50
 * Στο τέλος εμφανίζεται το πλήθος κάθε κατηγορίας
 * και ποια κατηγορία είχε τους περισσότερους αριθμούς.
 */

#include <iostream>
using namespace std;

int main() {
    int num;
    int low = 0, mid = 0, high = 0;
    
    do {
        cout << "Αριθμός (0=τέλος): ";
        cin >> num;
        
        if (num != 0) {
            if (num < 10) {
                low++;
            } else if (num <= 50) {
                mid++;
            } else {
                high++;
            }
        }
    } while (num != 0);
    
    cout << "<10: " << low << endl;
    cout << "10-50: " << mid << endl;
    cout << ">50: " << high << endl;
    
    return 0;
}
