/*
 * Άσκηση: Εύρεση Μέγιστου
 * Επίπεδο: 1
 * 
 * Περιγραφή:
 * Διάβασε 6 αριθμούς από τον χρήστη.
 * Βρες και εμφάνισε τον μεγαλύτερο.
 * 
 * Παράδειγμα:
 * Είσοδος: 5, 12, 3, 8, 15, 7
 * Έξοδος: Μέγιστο: 15
 */

#include <iostream>
using namespace std;

int main() {
    int number;
    int max = -999999;  // Ξεκινάμε με πολύ μικρή τιμή
    
    cout << "Δώσε 6 αριθμούς:" << endl;
    
    // ΛΥΣΗ: For loop με if για εύρεση μέγιστου
    for (int i = 1; i <= 6; i++) {
        cout << "Αριθμός " << i << ": ";
        cin >> number;
        
        if (number > max) {
            max = number;
        }
    }
    
    cout << "Μέγιστο: " << max << endl;
    
    return 0;
}
