/*
 * Άσκηση: Άθροισμα Θετικών Αριθμών
 * Επίπεδο: 1
 * 
 * Περιγραφή:
 * Διάβασε 5 αριθμούς από τον χρήστη.
 * Πρόσθεσε στο άθροισμα ΜΟΝΟ τους θετικούς αριθμούς (> 0).
 * 
 * Παράδειγμα:
 * Είσοδος: 3, -2, 5, -1, 4
 * Έξοδος: Άθροισμα θετικών: 12 (3+5+4)
 */

#include <iostream>
using namespace std;

int main() {
    int number;
    int sum = 0;
    
    cout << "Δώσε 5 αριθμούς:" << endl;
    
    // ΛΥΣΗ: For loop με if μέσα
    for (int i = 1; i <= 5; i++) {
        cout << "Αριθμός " << i << ": ";
        cin >> number;
        
        if (number > 0) {
            sum = sum + number;
        }
    }
    
    cout << "Άθροισμα θετικών: " << sum << endl;
    
    return 0;
}
