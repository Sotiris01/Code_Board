# ΑΣΚΗΣΗ: Αριθμητικές Εκφράσεις - ΛΥΣΗ

ekf1 = 15 + 2 / 2          # 2/2=1, 15+1=16.0
ekf2 = 5 * (3 + 2) / 10    # 5*5=25, 25/10=2.5
ekf3 = 2 ** 3 * 3 ** 2     # 8 * 9 = 72
ekf4 = 8 // 4 % 2          # 2 % 2 = 0
ekf5 = 11 % 3 - 2 * 2      # 2 - 4 = -2

print("15 + 2 / 2 =", ekf1)
print("5 * (3 + 2) / 10 =", ekf2)
print("2 ** 3 * 3 ** 2 =", ekf3)
print("8 // 4 % 2 =", ekf4)
print("11 % 3 - 2 * 2 =", ekf5)
