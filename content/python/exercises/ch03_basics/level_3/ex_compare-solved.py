# ΑΣΚΗΣΗ: Σύγκριση Δύο Αριθμών - ΛΥΣΗ

a = int(input("Δώσε αριθμό Α: "))
b = int(input("Δώσε αριθμό Β: "))

if a > b:
    print("Ο a (" + str(a) + ") είναι μεγαλύτερος από τον b (" + str(b) + ")")
elif a < b:
    print("Ο b (" + str(b) + ") είναι μεγαλύτερος από τον a (" + str(a) + ")")
else:
    print("Οι αριθμοί είναι ίσοι")
