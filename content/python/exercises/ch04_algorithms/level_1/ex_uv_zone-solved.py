# ΑΣΚΗΣΗ: Ζώνη Κινδύνου UV - ΛΥΣΗ

uv = int(input("Δώσε δείκτη UV: "))

if uv <= 15:
    if uv >= 11:
        print("Ακραία κατάσταση κινδύνου")
    elif uv >= 6:
        print("Μεγάλος κίνδυνος")
    elif uv >= 0:
        print("Ελάχιστος κίνδυνος")
    else:
        print("Μη αποδεκτή τιμή!")
else:
    print("Μη αποδεκτή τιμή!")
